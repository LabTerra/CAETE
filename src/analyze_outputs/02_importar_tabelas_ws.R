# ============================================================
# CAETE - Import simulation outputs into R
# ============================================================
#
# DESCRIPTION:
# This script imports the daily simulation outputs previously
# extracted from CAETE .pkz files using the Python extraction script 01_extract_daily_and_area_manual.py
#
# It loads three datasets:
#   1. pls_attrs: Functional traits of each Plant Life Strategy (PLS).
#   2. diario: Daily ecosystem-level simulation outputs
#      (e.g., GPP, NPP, LAI, evapotranspiration).
#   3. area: Daily relative occupation of each PLS in the grid cell.
#
# REQUIREMENTS:
#   R (no additional packages required).
#
# HOW TO USE:
#   1. Update the paths below to match your computer.
#   2. Make sure diario.csv and area.csv have been generated
#      using the 01_extract_daily_and_area_manual.py script.
#   3. Run this script in R or RStudio.
#   4. Check the imported tables before starting your analysis.
#
# ============================================================


# ====================== USER SETTINGS =======================

# Folder containing the CSV files generated by Python
folder <- "~/Documents/CAETE/docs/<your_analysis_folder>/tabelas"

# Path to the PLS functional traits table
pls_file <- "~/Documents/CAETE/outputs/<run_name>/pls_attrs-3000.csv"


# ====================== IMPORT DATA =========================

# Functional traits of the PLSs
pls_attrs <- read.csv(pls_file)

# Daily ecosystem-level outputs
diario <- read.csv(file.path(folder, "diario.csv"))

# Daily PLS occupation
area <- read.csv(file.path(folder, "area.csv"))


# ====================== EXPLORE DATA ========================

# Open tables in the RStudio data viewer
View(pls_attrs)
View(diario)
View(area)

# Check table dimensions
dim(pls_attrs)
dim(diario)
dim(area)

# Check available variables
names(pls_attrs)
names(diario)
names(area)